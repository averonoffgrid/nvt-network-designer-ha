class MqttBridge:
    def __init__(self):
        self.client=None
        self.connected=False
        self.lock=threading.RLock()
        self.last_error=""
        self.project=empty_project()

    def service_info(self):
        token=os.environ.get("SUPERVISOR_TOKEN","")
        if not token: raise RuntimeError("SUPERVISOR_TOKEN unavailable")
        req=urllib.request.Request("http://supervisor/services/mqtt",
            headers={"Authorization":f"Bearer {token}","Content-Type":"application/json"})
        with urllib.request.urlopen(req,timeout=5) as r:
            obj=json.loads(r.read().decode())
        return obj.get("data",obj)

    def start(self):
        try:
            info=self.service_info()
            c=mqtt.Client(mqtt.CallbackAPIVersion.VERSION2,client_id="nvt-designer-node0")
            if info.get("username"): c.username_pw_set(info.get("username"),info.get("password"))
            if info.get("ssl"): c.tls_set(cert_reqs=ssl.CERT_NONE); c.tls_insecure_set(True)
            c.on_connect=self.on_connect; c.on_message=self.on_message
            c.connect(str(info["host"]),int(info["port"]),60)
            c.loop_start()
            self.client=c
        except Exception as e:
            self.last_error=str(e)

    def on_connect(self,client,userdata,flags,reason_code,properties):
        self.connected=True
        client.subscribe("nvt/+/set/+")
        client.subscribe("homeassistant/status")
        self.sync_project(load_project(),force=True)

    def on_message(self,client,userdata,msg):
        topic=msg.topic
        if topic=="homeassistant/status":
            if msg.payload.decode(errors="ignore").lower()=="online":
                self.sync_project(load_project(),force=True)
            return
        parts=topic.split("/")
        if len(parts)!=4 or parts[0]!="nvt" or parts[2]!="set": return
        uuid=parts[1].upper()
        try: var_id=int(parts[3])
        except ValueError: return
        payload=msg.payload.decode(errors="ignore").strip()
        self.direct_write(uuid,var_id,payload)

    def direct_write(self,uuid:str,var_id:int,payload:str):
        # Simulator implementation of Node0 DIRECT_WRITE.
        if OPTIONS["mode"]!="simulator":
            # Serial backend will encode NVT_MGMT_DIRECT_WRITE to CH32.
            self.last_error="DIRECT_WRITE serial transport not connected yet"
            return
        s=load_sim()
        dev=next((d for d in s["devices"] if d["uuid"].upper()==uuid),None)
        if not dev or dev.get("node_id") is None: return
        p=PROFILES[int(dev["profile_id"])]
        v=next((x for x in p["variables"] if int(x["var_id"])==var_id),None)
        if not v or v["direction"] not in ("subscribe","both"): return
        tid=v["nvt_type"]
        try:
            if tid=="NVT_SWITCH": value=payload.upper() in ("ON","1","TRUE")
            elif tid in ("NVT_TEMP","NVT_VOLT"): value=float(payload)
            elif tid=="NVT_PERCENT": value=max(0,min(100,float(payload)))
            else: value=payload
        except Exception: return
        s.setdefault("runtime",{}).setdefault("values",{})[variable_key(int(dev["node_id"]),var_id)]=value
        save_sim(s)
        self.publish_state(uuid,var_id,value,tid)

    def publish(self,topic,payload,retain=False):
        if self.client and self.connected:
            self.client.publish(topic,payload,qos=0,retain=retain)

    def publish_state(self,uuid,var_id,value,nvt_type):
        if value is None: return
        if nvt_type=="NVT_SWITCH": payload="ON" if bool(value) else "OFF"
        else: payload=str(value)
        self.publish(f"nvt/{uuid.lower()}/state/{var_id}",payload,retain=True)

    def entity_component(self,v):
        tid=v["nvt_type"]; writable=v["direction"] in ("subscribe","both")
        if writable:
            if tid=="NVT_SWITCH": return "switch"
            if tid in ("NVT_TEMP","NVT_PERCENT","NVT_VOLT"): return "number"
        if tid=="NVT_SWITCH": return "binary_sensor"
        return "sensor"

    def entity_config(self,node,d,v):
        uuid=d["uuid"].lower(); vid=int(v["var_id"]); component=self.entity_component(v)
        name=v["name"]
        unique=f"nvt_{uuid}_{vid}"
        state_topic=f"nvt/{uuid}/state/{vid}"
        cfg={
            "name":name,
            "unique_id":unique,
            "state_topic":state_topic,
            "device":{
                "identifiers":[f"nvt_{uuid}"],
                "name":node.get("name") or d.get("name") or f"Node {d.get('node_id')}",
                "manufacturer":"NVT Automation",
                "model":PROFILES[int(d["profile_id"])]["profile_name"],
                "serial_number":d["uuid"],
                "sw_version":d.get("fw_version",""),
                "hw_version":d.get("hw_version","")
            },
            "origin":{"name":"NVT Network Designer","sw_version":APP_VERSION}
        }
        if component=="binary_sensor":
            cfg.update({"payload_on":"ON","payload_off":"OFF"})
        if component=="switch":
            cfg.update({"command_topic":f"nvt/{uuid}/set/{vid}","payload_on":"ON","payload_off":"OFF"})
        if component=="number":
            cfg["command_topic"]=f"nvt/{uuid}/set/{vid}"
            if v["nvt_type"]=="NVT_PERCENT": cfg.update({"min":0,"max":100,"step":1,"unit_of_measurement":"%"})
            elif v["nvt_type"]=="NVT_TEMP": cfg.update({"min":-50,"max":100,"step":0.1,"unit_of_measurement":"°C"})
            elif v["nvt_type"]=="NVT_VOLT": cfg.update({"min":0,"max":100,"step":0.01,"unit_of_measurement":"V"})
        if component=="sensor":
            if v.get("unit"): cfg["unit_of_measurement"]=v["unit"]
            if v["nvt_type"]=="NVT_TEMP": cfg["device_class"]="temperature"
            if v["nvt_type"]=="NVT_VOLT": cfg["device_class"]="voltage"
        return component,unique,cfg

    def sync_project(self,project,force=False):
        self.project=project
        if not self.connected: return {"mqtt":False,"entities":0}
        s=load_sim()
        by_uuid={d["uuid"]:d for d in s["devices"]}
        current=[]
        count=0
        for node in project.get("nodes",[]):
            d=by_uuid.get(node["uuid"])
            if not d or d.get("node_id") is None: continue
            p=PROFILES[int(d["profile_id"])]
            for v in p["variables"]:
                component,obj,cfg=self.entity_config(node,d,v)
                topic=f"homeassistant/{component}/{obj}/config"
                current.append(topic)
                self.publish(topic,json.dumps(cfg,separators=(",",":")),retain=True)
                count+=1
        old=[]
        if HA_TOPICS_FILE.exists():
            try: old=json.loads(HA_TOPICS_FILE.read_text())
            except Exception: old=[]
        for topic in set(old)-set(current):
            self.publish(topic,"",retain=True)
        HA_TOPICS_FILE.write_text(json.dumps(current,indent=2))
        return {"mqtt":True,"entities":count}

