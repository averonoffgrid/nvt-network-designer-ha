def validate_binding(b,devices):
    sn=devices.get(b["source_node"]); tn=devices.get(b["target_node"])
    if not sn or not tn:return "node missing"
    sp=PROFILES[sn["profile_id"]]; tp=PROFILES[tn["profile_id"]]
    sv=next((v for v in sp["variables"] if v["var_id"]==b["source_var"]),None)
    tv=next((v for v in tp["variables"] if v["var_id"]==b["target_var"]),None)
    if not sv or not tv:return "variable missing"
    if sv["nvt_type"]!=tv["nvt_type"]:return f"type mismatch {sv['nvt_type']} -> {tv['nvt_type']}"
    if sv["direction"] not in ("publish","both"):return "source is not publish-capable"
    if tv["direction"] not in ("subscribe","both"):return "target is not subscribe-capable"
    return None

@app.post("/api/deploy")
def deploy(project:dict[str,Any]):
    if OPTIONS["mode"]!="simulator": raise HTTPException(501,"Serial deploy not connected yet.")
    s=load_sim()
    # project name is authoritative for the device display name
    by_uuid={n["uuid"]:n for n in project.get("nodes",[])}
    for d in s["devices"]:
        n=by_uuid.get(d["uuid"])
        if n and n.get("name"): d["name"]=n["name"]
    devices={d["node_id"]:d for d in s["devices"] if d.get("node_id") is not None}
    grouped={}; errors=[]
    for b in project.get("bindings",[]):
        err=validate_binding(b,devices)
        if err: errors.append({"binding":b.get("id"),"error":err}); continue
        grouped.setdefault(str(b["target_node"]),[]).append({
            "source_node":b["source_node"],"source_var":b["source_var"],
            "local_var":b["target_var"],"operation":b.get("operation","COPY")
        })
    if errors: raise HTTPException(422,json.dumps({"errors":errors}))
    s["deployed"]=grouped
    s.setdefault("runtime",{}).setdefault("values",{})
    s["runtime"]["last_propagation"]={}
    save_sim(s)
    PROJECT_FILE.write_text(json.dumps(project,indent=2,ensure_ascii=False))
    ha=MQTT.sync_project(project,force=True)
    return {"ok":True,"nodes":len(grouped),"bindings":sum(map(len,grouped.values())),
            "details":grouped,"ha":ha}

