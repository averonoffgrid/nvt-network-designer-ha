class CommissionRequest(BaseModel):
    uuid:str
    node_id:int=Field(ge=1,le=65533)

@app.post("/api/network/commission")
def commission(req:CommissionRequest):
    if OPTIONS["mode"]!="simulator": raise HTTPException(501,"Serial commissioning not connected yet.")
    s=load_sim()
    if any(d.get("node_id")==req.node_id for d in s["devices"]): raise HTTPException(409,"NODE_ID already in use")
    for d in s["devices"]:
        if d["uuid"].upper()==req.uuid.upper():
            if d.get("node_id") is not None: raise HTTPException(409,"Already commissioned")
            d["node_id"]=req.node_id; save_sim(s); return device_view(d)
    raise HTTPException(404,"UUID not found")

