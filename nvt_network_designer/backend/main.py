def variable_key(node_id:int,var_id:int)->str: return f"{node_id}:{var_id}"
def binding_key(s:int,sv:int,t:int,tv:int)->str: return f"{s}:{sv}->{t}:{tv}"

def generated_source_value(nid:int,v:dict[str,Any],now_ms:int):
    tid=v["nvt_type"]; vid=int(v["var_id"])
    if tid=="NVT_SWITCH": return bool((now_ms//3500+nid+vid)%2)
    if tid=="NVT_TEMP": return round(20.0+((nid*7+vid*3)%35)/10+((now_ms//1000)%10)/100,2)
    if tid=="NVT_PERCENT": return int((now_ms//250+nid*11+vid*7)%101)
    if tid=="NVT_VOLT": return round(1.0+((nid+vid)%20)/10,2)
    return 0

def build_runtime(s:dict[str,Any]):
    now=int(time.time()*1000)
    rt=s.setdefault("runtime",{})
    values=rt.setdefault("values",{})
    last_sources=rt.setdefault("last_sources",{})
    last_prop=rt.setdefault("last_propagation",{})
    devices={d["node_id"]:d for d in s["devices"] if d.get("node_id") is not None}

    # physical/publisher generation; writable overrides are respected for subscriber-only vars
    for nid,d in devices.items():
        p=PROFILES[int(d["profile_id"])]
        for v in p["variables"]:
            k=variable_key(nid,int(v["var_id"]))
            if v["direction"] in ("publish","both"):
                # For 'both' variables, explicit HA writes persist until a device-specific profile
                # decides otherwise. Pure publishers are generated by the simulator.
                if v["direction"]=="publish" or k not in values:
                    values[k]=generated_source_value(nid,v,now)
            else:
                values.setdefault(k,None)

    deployed=s.get("deployed",{})
    changed=True; passes=0; max_passes=max(2,len(devices)*2)
    while changed and passes<max_passes:
        changed=False; passes+=1
        for target_s,bindings in deployed.items():
            target=int(target_s)
            for b in bindings:
                sk=variable_key(int(b["source_node"]),int(b["source_var"]))
                dk=variable_key(target,int(b["local_var"]))
                if sk not in values or values[sk] is None: continue
                if values.get(dk)!=values[sk]:
                    values[dk]=values[sk]; changed=True
                    last_prop[binding_key(int(b["source_node"]),int(b["source_var"]),target,int(b["local_var"]))]=now

    for k,val in list(values.items()):
        if k in last_sources and last_sources[k]!=val:
            sn,sv=[int(x) for x in k.split(":")]
            for ts,bindings in deployed.items():
                for b in bindings:
                    if int(b["source_node"])==sn and int(b["source_var"])==sv:
                        last_prop[binding_key(sn,sv,int(ts),int(b["local_var"]))]=now
        last_sources[k]=val

    rt["last_propagation"]={k:v for k,v in last_prop.items() if int(v)>=now-30000}
    live=[]
    for nid,d in devices.items():
        p=PROFILES[int(d["profile_id"])]
        for v in p["variables"]:
            live.append({"node_id":nid,"var_id":int(v["var_id"]),
                         "value":values.get(variable_key(nid,int(v["var_id"]))),
                         "updated_ms":now,"direction":v["direction"]})
    save_sim(s)
    recent=[k for k,t in rt["last_propagation"].items() if now-int(t)<=1400]
    return {"values":live,"active_bindings":recent,"now_ms":now}

