def runtime_worker():
    while True:
        try:
            if OPTIONS["mode"]=="simulator":
                s=load_sim(); r=build_runtime(s)
                by_node={d["node_id"]:d for d in s["devices"] if d.get("node_id") is not None}
                for item in r["values"]:
                    d=by_node.get(item["node_id"])
                    if not d: continue
                    p=PROFILES[int(d["profile_id"])]
                    v=next((x for x in p["variables"] if int(x["var_id"])==item["var_id"]),None)
                    if v: MQTT.publish_state(d["uuid"],item["var_id"],item["value"],v["nvt_type"])
        except Exception as e:
            MQTT.last_error=str(e)
        time.sleep(0.5)

@app.on_event("startup")
def startup_event():
    MQTT.start()
    threading.Thread(target=runtime_worker,daemon=True,name="nvt-runtime").start()

